// Writes public/_redirects (Netlify format) so every old WordPress URL lands
// somewhere useful. Page decisions come from docs/content-map.md; attachment
// pages come from migration/wp-export/attachments.json. Run: npm run redirects
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);

// Old path -> new path. Keep in sync with the table in docs/content-map.md.
const pageRedirects = [
  ['/mini-cows/', '/mini-oxen/'],
  ['/terms-conditions/', '/'],
  ['/online-store/', '/farm-store/'],
  ['/products-list/', '/farm-store/'],
  ['/alprilla-order-page/', '/farm-store/'],
  ['/cart/', '/farm-store/'],
  ['/checkout/', '/farm-store/'],
  ['/my-account/', '/farm-store/'],
  ['/my-account/*', '/farm-store/'],
  ['/paypal-order-complete/', '/farm-store/'],
  ['/shop/', '/farm-store/'],
  ['/shop/*', '/farm-store/'],
  ['/product/*', '/farm-store/'],
  ['/product-category/*', '/farm-store/'],
  ['/category/*', '/'],
  ['/feed/', '/'],
  ['/feed/*', '/'],
];

// A page that moved also takes its attachment pages with it.
const moved = new Map(pageRedirects.filter(([from]) => !from.includes('*')));
const attachments = JSON.parse(
  await readFile(new URL('migration/wp-export/attachments.json', root), 'utf8'),
);
const attachmentRedirects = attachments.map(({ attachment_path, parent_path }) => {
  const parent = parent_path ?? '/';
  return [attachment_path, moved.get(parent) ?? parent];
});

const lines = [
  '# Generated by migration/build-redirects.mjs. Do not edit by hand.',
  '# Netlify only applies these when no file exists at the old path.',
  '',
  '# Pages',
  ...pageRedirects.map(([from, to]) => `${from}  ${to}  301`),
  '',
  '# WordPress attachment pages -> the page the image belonged to',
  ...attachmentRedirects.map(([from, to]) => `${from}  ${to}  301`),
  '',
];

await writeFile(new URL('public/_redirects', root), lines.join('\n'));
console.log(`Wrote ${pageRedirects.length} page + ${attachmentRedirects.length} attachment redirects to public/_redirects`);
